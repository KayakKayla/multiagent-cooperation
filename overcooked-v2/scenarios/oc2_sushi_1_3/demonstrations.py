"""Audited action-derived sushi demonstrations for supervised policy training.

Observation t precedes action t; that action produces state t+1. Seeds vary
harmless joint-STAY delays, optional movement prefixes, and optional route ties.
All trajectories start at env.reset and are generated by real actions; no state is edited.
"""
from collections import deque
from dataclasses import asdict
from functools import lru_cache
import argparse
import hashlib
import json
from pathlib import Path

import jax
import numpy as np

from .environment import Action, State
from .scripted import Script, compare_reference
from .layout import Tile


@lru_cache(maxsize=4)
def _environment(agent_view_size):
    from scenarios import make_env
    return make_env("oc2_sushi_1_3", agent_view_size=agent_view_size)


@lru_cache(maxsize=1)
def _reference_steps():
    # Derive the available delay budget from the actual audited workflow.
    return len(Script(_environment(None)).run().actions) - 1


class _DelayedScript(Script):
    def __init__(self, env, seed, random_wait_max, delay_budget, randomize_routes=False, prefix_attempt=0):
        super().__init__(env)
        self.rng = np.random.default_rng(seed)
        self.random_wait_max = random_wait_max
        self.delay_budget = delay_budget
        self.inserted_waits = 0
        self.supervision = []
        self.randomize_routes = randomize_routes
        self.prefix_rng = np.random.default_rng(np.random.SeedSequence([seed, 0xA17, prefix_attempt]))
        self.route_rng = np.random.default_rng(np.random.SeedSequence([seed, 0xC31, prefix_attempt]))
        self.prefix_actions = []
        self.route_direction_orders = []

    def advance(self, agent, action, label, require_success=False):
        remaining = self.delay_budget - self.inserted_waits
        if action != Action.STAY and self.random_wait_max and remaining:
            upper = min(self.random_wait_max, remaining)
            extra = int(self.rng.integers(0, upper + 1))
            for _ in range(extra):
                # Script.advance supplies STAY to the other chef, too.
                super().advance(0, Action.STAY, "Demonstration delay")
                self.supervision.append(False)
            self.inserted_waits += extra
        result = super().advance(agent, action, label, require_success)
        self.supervision.append(True)
        return result


    def prefix(self, steps, recorded=None):
        """Execute one-chef-at-a-time legal moves/STAY, never pickup or work."""
        terrain = np.asarray(self.env.tiles)
        directions = ((1, 0), (0, 1), (-1, 0), (0, -1))
        for t in range(steps):
            if recorded is None:
                agent = int(self.prefix_rng.integers(0, 2))
                positions = np.asarray(self.state.positions)
                x, y = map(int, positions[agent])
                other = tuple(map(int, positions[1 - agent]))
                legal = [int(Action.STAY)]
                for action, (dx, dy) in enumerate(directions):
                    nx, ny = x + dx, y + dy
                    if (0 <= nx < self.env.width and 0 <= ny < self.env.height
                            and terrain[ny, nx] == Tile.FLOOR and (nx, ny) != other):
                        legal.append(action)
                action = int(self.prefix_rng.choice(legal))
            else:
                pair = recorded[t]
                agent = 0 if pair[0] != Action.STAY else 1
                action = int(pair[agent])
            # Bypass the augmentation override: prefix choices are not expert labels.
            super().advance(agent, action, "Unsupervised movement prefix")
            self.supervision.append(False)
            self.prefix_actions.append(list(self.actions[-1]))
        initial = self.states[0]
        for field in ("kind", "location", "contents", "progress", "return_due"):
            if not np.array_equal(getattr(initial, field), getattr(self.state, field)):
                raise AssertionError("Movement prefix changed kitchen resources")
        return self

    def approach(self, agent, station, label):
        if not self.randomize_routes:
            return super().approach(agent, station, label)
        # Same shortest-path rule as Script; only equal-cost traversal order varies.
        env = self.env
        start = tuple(map(int, self.state.positions[agent]))
        other = tuple(map(int, self.state.positions[1 - agent]))
        directions = ((1, 0), (0, 1), (-1, 0), (0, -1))
        order = self.route_rng.permutation(4).tolist()
        self.route_direction_orders.append({"agent": int(agent), "station": list(station), "order": order})
        goals = {(station[0] - dx, station[1] - dy): action for action, (dx, dy) in enumerate(directions)}
        queue, paths = deque([start]), {start: []}
        chosen = None
        while queue:
            point = queue.popleft()
            if point in goals:
                chosen = point
                break
            for action in order:
                dx, dy = directions[action]
                nxt = point[0] + dx, point[1] + dy
                x, y = nxt
                if (nxt not in paths and nxt != other and 0 <= x < env.width and 0 <= y < env.height
                        and int(env.tiles[y, x]) == Tile.FLOOR):
                    paths[nxt] = paths[point] + [action]
                    queue.append(nxt)
        if chosen is None:
            raise RuntimeError(f"No route for chef {agent} to {station}")
        for action in paths[chosen]:
            self.advance(agent, action, label)
        facing = goals[chosen]
        if int(self.state.directions[agent]) != facing:
            self.advance(agent, facing, label)


def _preflight(env, seed, prefix_steps, randomize_routes):
    """Derive the actual route budget without editing or synthesizing any state."""
    failures = []
    limit = min(512, env.max_steps - 1)
    for attempt in range(8):
        try:
            plan = _DelayedScript(env, seed, 0, 0, randomize_routes, attempt)
            plan.prefix(prefix_steps).run()
            compare_reference(plan)
            steps = len(plan.actions) - 1
            if steps > limit:
                raise RuntimeError(f"Expert plan requires {steps} steps; limit is {limit}")
            return steps, plan.prefix_actions, attempt, failures
        except RuntimeError as error:
            # Some legal joint positions obstruct a narrow passage. Try another
            # action-derived prefix/tie order; retain every rejection reason.
            failures.append(str(error))
    raise RuntimeError("Unable to generate an audited bounded demonstration: " + "; ".join(failures))


def generate_demo(seed, agent_view_size=None, random_wait_max=2,
                  prefix_random_steps=0, randomize_routes=False,
                  discard_prefix_context=False):
    """Return a two-delivery, washed-plate demonstration from real simulator actions.

    ``agent_view_size=None`` gives full-map observations. The original local view
    is available with ``agent_view_size=2``. Delays are globally capped at 96 steps
    and the remaining episode budget. Repeating a seed reproduces the trajectory.
    Generation explicitly uses CPU, leaving the GPU free for policy updates.
    Randomly inserted delays have zero supervision_mask for both chefs. Their
    observations/actions remain in the history, but do not teach arbitrary waits.
    An optional prefix of 0..64 legal moves/STAY similarly receives zero loss;
    the expert then plans from its actual result. Optional route randomization
    varies BFS ties. Preflight keeps the entire record within 512 steps and the
    original 600-step episode. Defaults preserve the previous demonstration paths.
    ``discard_prefix_context=True`` slices away executed prefix transitions after
    the complete audit, so a zero-hidden-state learner starts at that real pose.
    Its initial State.time remains positive; no state value is rewritten.
    """
    if isinstance(seed, bool) or not isinstance(seed, (int, np.integer)) or not 0 <= seed < 2**32:
        raise ValueError("seed must be an unsigned 32-bit integer")
    if isinstance(random_wait_max, bool) or not isinstance(random_wait_max, (int, np.integer)) or random_wait_max < 0:
        raise ValueError("random_wait_max must be a nonnegative integer")
    if agent_view_size is not None and (
        isinstance(agent_view_size, bool) or not isinstance(agent_view_size, int) or agent_view_size < 0
    ):
        raise ValueError("agent_view_size must be None or a nonnegative integer")
    if (isinstance(prefix_random_steps, bool) or not isinstance(prefix_random_steps, (int, np.integer))
            or not 0 <= prefix_random_steps <= 64):
        raise ValueError("prefix_random_steps must be an integer from 0 to 64")
    if not isinstance(randomize_routes, bool):
        raise ValueError("randomize_routes must be a boolean")
    if not isinstance(discard_prefix_context, bool):
        raise ValueError("discard_prefix_context must be a boolean")
    with jax.default_device(jax.devices("cpu")[0]):
        env = _environment(agent_view_size)
        original_reference_steps = _reference_steps()
        prefix_actions, prefix_attempt, failures = [], 0, []
        reference_steps = original_reference_steps
        if prefix_random_steps or randomize_routes:
            reference_steps, prefix_actions, prefix_attempt, failures = _preflight(
                env, int(seed), int(prefix_random_steps), randomize_routes)
        trajectory_budget = min(512, env.max_steps - 1)
        # STAY never changes routes; extra passive cooking can shorten waits.
        delay_budget = max(0, min(96, trajectory_budget - reference_steps))
        script = _DelayedScript(env, int(seed), int(random_wait_max), delay_budget,
                                randomize_routes, prefix_attempt)
        script.prefix(int(prefix_random_steps), recorded=prefix_actions).run()
        reference = compare_reference(script)  # Includes both complete plate cycles.
        actions = np.asarray(script.actions[1:], dtype=np.int32)
        before = jax.tree.map(lambda *parts: np.stack(parts), *script.states[:-1])
        observations = jax.jit(jax.vmap(env.get_obs))(before)
        observations = np.stack([np.asarray(observations[a]) for a in env.agents], axis=1).astype(np.float32)
        states = tuple(jax.device_get(script.states))
    original_steps = len(actions)
    assert original_steps <= trajectory_budget and original_steps < env.max_steps and int(states[-1].deliveries) == 2
    mask = np.repeat(np.asarray(script.supervision, dtype=np.float32)[:, None], 2, axis=1)
    assert mask.shape == actions.shape
    discarded = int(prefix_random_steps) if discard_prefix_context else 0
    if discarded:
        observations, actions, mask = observations[discarded:], actions[discarded:], mask[discarded:]
        states = states[discarded:]
    steps = len(actions)
    assert observations.shape == (steps, 2, *env.obs_shape) and len(states) == steps + 1
    milestones = script.milestones
    if discarded:
        milestones = [dict(entry, absolute_step=entry["step"], step=entry["step"] - discarded)
                      for entry in script.milestones]
    metadata = {
        "schema_version": 1,
        "layout": env.name,
        "seed": int(seed),
        "seed_scope": "joint-STAY delays, optional movement prefixes/BFS ties; original reset and recipe fixed",
        "agent_view_size": agent_view_size,
        "agents": list(env.agents),
        "steps": steps,
        "deliveries": int(states[-1].deliveries),
        "random_wait_max": int(random_wait_max),
        "inserted_wait_steps": script.inserted_waits,
        "delay_budget": delay_budget,
        "reference_steps": reference_steps - discarded,
        "preflight_trajectory_steps": reference_steps,
        "original_trajectory_steps": original_steps,
        "discard_prefix_context": discard_prefix_context,
        "discarded_prefix_steps": discarded,
        "initial_state_time": int(states[0].time),
        "initial_state_origin": "after recorded legal-prefix actions" if discarded else "env.reset",
        "original_milestones": script.milestones,
        "original_reference_steps": original_reference_steps,
        "trajectory_budget": trajectory_budget,
        "prefix_random_steps": int(prefix_random_steps),
        "prefix_actions": script.prefix_actions,
        "prefix_action_counts": [np.bincount(np.asarray(script.prefix_actions, dtype=np.int32).reshape(-1, 2)[:, agent],
                                            minlength=5).tolist() for agent in range(2)],
        "prefix_attempt": prefix_attempt,
        "prefix_preflight_rejections": failures,
        "expert_start_positions": np.asarray(script.states[int(prefix_random_steps)].positions).tolist(),
        "expert_start_directions": np.asarray(script.states[int(prefix_random_steps)].directions).tolist(),
        "prefix_kitchen_unchanged": True,
        "randomize_routes": randomize_routes,
        "route_direction_orders": script.route_direction_orders,
        "alignment": "observations[t] = get_obs(states[t]); actions[t] produces states[t+1]",
        "rules": asdict(env.rules),
        "milestones": milestones,
        "semantic_reference_passed": reference["semantic_checkpoints_passed"],
        "source_sha256": {
            name: hashlib.sha256(Path(__file__).with_name(name).read_bytes()).hexdigest()
            for name in ("environment.py", "layout.py", "scripted.py", "demonstrations.py")
        },
    }
    metadata["supervised_agent_decisions"] = int(mask.sum())
    return {"observations": observations, "actions": actions,
            "supervision_mask": mask, "lengths": np.asarray(steps, dtype=np.int32),
            "states": states, "metadata": metadata}


def save_demo(demo, path):
    """Save numerical arrays and JSON metadata; loading requires no pickle."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    arrays = {
        "observations": demo["observations"],
        "actions": demo["actions"],
        "supervision_mask": demo["supervision_mask"],
        "lengths": demo["lengths"],
        "metadata_json": np.asarray(json.dumps(demo["metadata"], sort_keys=True)),
    }
    arrays.update({
        "state_" + field: np.stack([getattr(state, field) for state in demo["states"]])
        for field in State._fields
    })
    np.savez_compressed(path, **arrays)
    return path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--agent-view-size", type=int, default=None, help="Omit for full map; use 2 for local views.")
    parser.add_argument("--random-wait-max", type=int, default=2)
    parser.add_argument("--prefix-random-steps", type=int, default=0)
    parser.add_argument("--randomize-routes", action="store_true")
    parser.add_argument("--discard-prefix-context", action="store_true")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    demo = generate_demo(args.seed, args.agent_view_size, args.random_wait_max,
                         args.prefix_random_steps, args.randomize_routes,
                         args.discard_prefix_context)
    path = save_demo(demo, args.output)
    print(json.dumps({"output": str(path), "steps": len(demo["actions"]),
                      "deliveries": demo["metadata"]["deliveries"],
                      "observations_shape": list(demo["observations"].shape),
                      "inserted_wait_steps": demo["metadata"]["inserted_wait_steps"],
                      "prefix_random_steps": demo["metadata"]["prefix_random_steps"],
                      "randomize_routes": demo["metadata"]["randomize_routes"],
                      "discarded_prefix_steps": demo["metadata"]["discarded_prefix_steps"]}, indent=2))


if __name__ == "__main__":
    main()
